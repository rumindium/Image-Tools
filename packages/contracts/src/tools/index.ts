export const TOOLS_BY_ID: ReadonlyMap<string, ToolDefinition> = new Map(
  CATALOG.map((tool) => [tool.id, tool]),
);

export function getTool(id: string): ToolDefinition {
  const tool = TOOLS_BY_ID.get(id);
  if (!tool) throw new Error(`Unknown tool id: ${id}`);
  return tool;
}

